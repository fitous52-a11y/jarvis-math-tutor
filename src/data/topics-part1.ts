import { randInt } from '../lib/math-utils';

// ============ 1. Сложение и вычитание натуральных чисел ============
const addsub: Topic = {
  id: 'addsub',
  title: 'Сложение и вычитание',
  scanName: 'сложение и вычитание натуральных чисел',
  icon: 'plus',
  theory: [
    {
      kind: 'text',
      body: 'Складывать и вычитать большие числа удобнее всего столбиком: цифры пишем друг под другом — единицы под единицами, десятки под десятками.',
    },
    {
      kind: 'rule',
      title: 'Главное правило',
      body: 'Считаем справа налево. Если при сложении в разряде получилось 10 или больше — единицу переносим в следующий разряд (запоминаем «1 в уме»).',
    },
    {
      kind: 'example',
      title: 'Пример: 457 + 268',
      body: 'Единицы: 7 + 8 = 15 → пишем 5, 1 в уме.\nДесятки: 5 + 6 + 1 = 12 → пишем 2, 1 в уме.\nСотни: 4 + 2 + 1 = 7.\nОтвет: 725.',
    },
    {
      kind: 'example',
      title: 'Пример: 502 − 137',
      body: 'Из 2 вычесть 7 нельзя — занимаем. У нуля занять нельзя, идём к сотням: 502 → 4 сотни, 9 десятков, 12 единиц.\n12 − 7 = 5; 9 − 3 = 6; 4 − 1 = 3.\nОтвет: 365.',
    },
    {
      kind: 'tip',
      body: 'Проверка: сложение проверяется вычитанием (725 − 268 = 457), а вычитание — сложением (365 + 137 = 502).',
    },
  ],
  generate() {
    const plus = Math.random() < 0.5;
    if (plus) {
      const a = randInt(128, 899), b = randInt(117, 899);
      const ans = a + b;
      return {
        prompt: `Вычисли столбиком:\n${a} + ${b}`,
        answer: String(ans),
        solution: [
          `Складываем по разрядам справа налево.`,
          `Единицы: ${a % 10} + ${b % 10} = ${(a % 10) + (b % 10)}${(a % 10) + (b % 10) >= 10 ? ' — пишем ' + ((a % 10) + (b % 10)) % 10 + ', 1 в уме' : ''}.`,
          `Десятки и сотни складываем так же, не забывая переносы.`,
          `Ответ: ${ans}.`,
        ],
        mistakes: [
          {
            test: (_s, n) => n !== null && Math.abs(n - ans) === 100,
            feedback: 'Ты ошибся ровно на сотню — скорее всего, забыл перенести «1 в уме» из десятков в сотни (или перенёс лишний раз). Пересчитай столбик: следи за каждым переносом.',
          },
          {
            test: (_s, n) => n !== null && Math.abs(n - ans) === 10,
            feedback: 'Ответ отличается ровно на 10 — похоже, потерялся перенос из единиц в десятки. Если в единицах получилось 10 или больше, не забудь прибавить единичку к десяткам.',
          },
          {
            test: (_s, n) => n !== null && Math.abs(n - ans) === 1,
            feedback: 'Ошибка на единицу — где-то в разряде посчитал чуть неточно. Проверь сложение в каждом разряде ещё раз, начиная с единиц.',
          },
        ],
        hint: 'Начни с единиц и двигайся влево. Следи за переносами «в уме».',
      };
    }
    let a = randInt(300, 999), b = randInt(128, 899);
    if (b > a) [a, b] = [b, a];
    const ans = a - b;
    return {
      prompt: `Вычисли столбиком:\n${a} − ${b}`,
      answer: String(ans),
      solution: [
        `Вычитаем по разрядам справа налево.`,
        `Если цифра сверху меньше — занимаем десяток из соседнего разряда.`,
        `Проверка: ${ans} + ${b} = ${a}.`,
        `Ответ: ${ans}.`,
      ],
      mistakes: [
        {
          test: (_s, n) => n !== null && Math.abs(n - ans) === 100,
          feedback: 'Ошибка ровно на сотню — при занимании через разряд что-то пошло не так. Помни: когда занимаем, соседний разряд уменьшается на 1.',
        },
        {
          test: (_s, n) => n !== null && Math.abs(n - ans) === 10,
          feedback: 'Ошибка ровно на 10 — проверь занимание в десятках: заняли ли ты десяток там, где цифра сверху была меньше.',
        },
        {
          test: (_s, n) => n !== null && n === a + b - 2 * Math.min(a % 10, b % 10) && false,
          feedback: 'Проверь разряд единиц: похоже, ты вычел меньшую цифру из большей, хотя сверху стояла меньшая. Вычитать нужно из верхнего числа нижнее, а если нельзя — занимать десяток.',
        },
      ],
      hint: 'Если сверху цифра меньше, чем снизу — занимай десяток слева.',
    };
  },
};

// ============ 2. Умножение и деление натуральных чисел ============
const muldiv: Topic = {
  id: 'muldiv',
  title: 'Умножение и деление',
  scanName: 'умножение и деление натуральных чисел',
  icon: 'x',
  theory: [
    {
      kind: 'text',
      body: 'Умножение — это быстрое сложение одинаковых чисел: 7 × 4 — это 7 + 7 + 7 + 7. Деление — обратное действие: оно отвечает на вопрос «сколько раз одно число помещается в другом».',
    },
    {
      kind: 'rule',
      title: 'Таблица умножения',
      body: 'Всё умножение и деление в 5 классе держится на таблице умножения. Если где-то «плывёшь» — чаще всего дело именно в ней.',
    },
    {
      kind: 'example',
      title: 'Умножение столбиком: 34 × 26',
      body: 'Сначала 34 × 6 = 204.\nПотом 34 × 20 = 680 (умножаем на 2 и дописываем ноль).\nСкладываем: 204 + 680 = 884.',
    },
    {
      kind: 'example',
      title: 'Деление уголком: 861 ÷ 7',
      body: '8 ÷ 7 = 1 (остаток 1). Сносим 6 → 16.\n16 ÷ 7 = 2 (остаток 2). Сносим 1 → 21.\n21 ÷ 7 = 3. Ответ: 123.',
    },
    {
      kind: 'tip',
      body: 'Проверка деления: умножь ответ на делитель — должно получиться делимое. 123 × 7 = 861. Значит, верно!',
    },
  ],
  generate(difficulty) {
    if (Math.random() < 0.5) {
      const a = difficulty === 1 ? randInt(12, 49) : randInt(23, 99);
      const b = randInt(4, 9);
      const ans = a * b;
      return {
        prompt: `Вычисли:\n${a} × ${b}`,
        answer: String(ans),
        solution: [
          `Умножаем столбиком: сначала ${a} × ${b} по разрядам.`,
          `Можно разложить: ${a} × ${b} = ${Math.floor(a / 10) * 10} × ${b} + ${a % 10} × ${b} = ${Math.floor(a / 10) * 10 * b} + ${(a % 10) * b}.`,
          `Ответ: ${ans}.`,
        ],
        mistakes: [
          {
            test: (_s, n) => n !== null && (n === ans * 10 || n === Math.round(ans / 10)),
            feedback: 'Ответ отличается в 10 раз — съехал разряд. Проверь, сколько цифр должно быть в ответе: двузначное × однозначное даёт трёхзначное число (примерно).',
          },
          {
            test: (_s, n) => n !== null && Math.abs(n - ans) === b,
            feedback: `Ответ отличается ровно на ${b} — похоже, в таблице умножения на ${b} сбился на одну ступеньку. Повтори столбик на ${b}.`,
          },
        ],
        hint: 'Разложи большое число на десятки и единицы и умножь каждую часть отдельно.',
      };
    }
    const b = randInt(3, 9);
    const q = difficulty === 1 ? randInt(12, 99) : randInt(102, 312);
    const a = b * q;
    return {
      prompt: `Вычисли:\n${a} ÷ ${b}`,
      answer: String(q),
      solution: [
        `Делим уголком: берём по разряду, пока не дойдём до конца.`,
        `Проверка: ${q} × ${b} = ${a}.`,
        `Ответ: ${q}.`,
      ],
      mistakes: [
        {
          test: (_s, n) => n !== null && n !== q && n * b === a,
          feedback: 'Странно, но твой ответ при проверке сходится... пересчитай ещё раз.',
        },
        {
          test: (_s, n) => n !== null && Math.abs(n * b - a) < b && n !== q,
          feedback: 'Очень близко! При делении уголком где-то потерялся остаток. Делай проверку: умножь свой ответ на делитель — должно получиться делимое.',
        },
        {
          test: (_s, n) => n !== null && (n === q * 10 || n === Math.round(q / 10)),
          feedback: 'Ответ отличается в 10 раз — потерялся или появился лишний ноль. Помни: нули в конце частного пишутся, когда остаток 0, а цифры ещё остались.',
        },
      ],
      hint: 'Проверь себя умножением: ответ × делитель должно дать делимое.',
    };
  },
};

// ============ 3. Порядок действий ============
const order: Topic = {
  id: 'order',
  title: 'Порядок действий',
  scanName: 'порядок действий в выражениях',
  icon: 'list-ordered',
  theory: [
    {
      kind: 'text',
      body: 'В выражении действия выполняются не просто слева направо, а по особым правилам — как уровни в игре.',
    },
    {
      kind: 'rule',
      title: 'Правило уровней',
      body: '1) Сначала — скобки.\n2) Потом — умножение и деление (слева направо).\n3) В конце — сложение и вычитание (слева направо).',
    },
    {
      kind: 'example',
      title: 'Пример: 24 + 6 × 3',
      body: 'Умножение сильнее сложения, поэтому сначала 6 × 3 = 18.\nПотом 24 + 18 = 42.\nА вот если считать слева направо, получится 90 — это и есть самая частая ловушка!',
    },
    {
      kind: 'example',
      title: 'Пример со скобками: (24 + 6) × 3',
      body: 'Скобки — первый уровень: 24 + 6 = 30.\nПотом 30 × 3 = 90.',
    },
    {
      kind: 'tip',
      body: 'Перед вычислением расставь номера действий над знаками — и ошибиться будет почти невозможно.',
    },
  ],
  generate() {
    const variant = randInt(0, 2);
    if (variant === 0) {
      const a = randInt(10, 60), b = randInt(3, 9), c = randInt(3, 9);
      const ans = a + b * c;
      const wrong = (a + b) * c;
      return {
        prompt: `Вычисли:\n${a} + ${b} × ${c}`,
        answer: String(ans),
        solution: [
          `Первым действием идёт умножение: ${b} × ${c} = ${b * c}.`,
          `Вторым — сложение: ${a} + ${b * c} = ${ans}.`,
          `Ответ: ${ans}.`,
        ],
        mistakes: [
          {
            test: (_s, n) => n === wrong,
            feedback: `Ты посчитал слева направо: сначала ${a} + ${b}, а потом умножил. Но умножение всегда выполняется раньше сложения! Правильно: сначала ${b} × ${c} = ${b * c}, потом ${a} + ${b * c} = ${ans}.`,
          },
        ],
        hint: 'Сначала умножение, потом сложение.',
      };
    }
    if (variant === 1) {
      const b = randInt(2, 9);
      const a = b * randInt(5, 15);
      const d = randInt(10, 60);
      const ans = a / b + d;
      const wrong = a / (b + d);
      return {
        prompt: `Вычисли:\n${a} ÷ ${b} + ${d}`,
        answer: String(ans),
        solution: [
          `Сначала деление: ${a} ÷ ${b} = ${a / b}.`,
          `Потом сложение: ${a / b} + ${d} = ${ans}.`,
          `Ответ: ${ans}.`,
        ],
        mistakes: [
          {
            test: (_s, n) => n === wrong,
            feedback: `Похоже, ты сначала сложил ${b} + ${d}, а потом делил. Но деление выполняется раньше сложения! Сначала ${a} ÷ ${b} = ${a / b}, потом прибавляем ${d}.`,
          },
        ],
        hint: 'Деление — перед сложением.',
      };
    }
    const a = randInt(12, 40), b = randInt(3, 9), c = randInt(2, 9);
    const ans = (a - c) * b;
    const wrong = a - c * b;
    return {
      prompt: `Вычисли:\n(${a} − ${c}) × ${b}`,
      answer: String(ans),
      solution: [
        `Сначала скобки: ${a} − ${c} = ${a - c}.`,
        `Потом умножение: ${a - c} × ${b} = ${ans}.`,
        `Ответ: ${ans}.`,
      ],
      mistakes: [
        {
          test: (_s, n) => n === wrong,
          feedback: `Ты проигнорировал скобки и сначала умножил. Скобки — самый первый уровень! Сначала ${a} − ${c} = ${a - c}, и только потом умножаем на ${b}.`,
        },
      ],
      hint: 'Скобки всегда первые!',
    };
  },
};

// ============ 4. Площадь и периметр ============
const area: Topic = {
  id: 'area',
  title: 'Площадь и периметр',
  scanName: 'площадь и периметр прямоугольника',
  icon: 'square',
  theory: [
    {
      kind: 'text',
      body: 'Периметр — это длина границы фигуры (как забор вокруг участка). Площадь — сколько места фигура занимает внутри (как газон внутри забора).',
    },
    {
      kind: 'rule',
      title: 'Формулы прямоугольника',
      body: 'Периметр: P = (a + b) × 2 — сложили длину и ширину и удвоили.\nПлощадь: S = a × b — длину умножили на ширину.\nДля квадрата: P = 4a, S = a × a.',
    },
    {
      kind: 'example',
      title: 'Пример: прямоугольник 5 см × 3 см',
      body: 'P = (5 + 3) × 2 = 16 см.\nS = 5 × 3 = 15 см².\nОбрати внимание: периметр измеряется в см, а площадь — в квадратных сантиметрах (см²).',
    },
    {
      kind: 'tip',
      body: 'Площадь всегда в «квадратных» единицах: см², м², км². Если в ответе нет квадратика — ты, скорее всего, нашёл периметр.',
    },
  ],
  generate() {
    const a = randInt(3, 15), b = randInt(2, 12);
    const askArea = Math.random() < 0.5;
    const S = a * b, P = 2 * (a + b);
    if (askArea) {
      return {
        prompt: `Найди площадь прямоугольника со сторонами ${a} см и ${b} см.\n(ответ запиши числом, без единиц)`,
        answer: String(S),
        solution: [
          `Площадь прямоугольника: S = a × b.`,
          `S = ${a} × ${b} = ${S}.`,
          `Ответ: ${S} (см²).`,
        ],
        mistakes: [
          {
            test: (_s, n) => n === P,
            feedback: `Ты нашёл периметр (${P}), а не площадь! Периметр — это сумма всех сторон, а площадь — произведение длины на ширину: ${a} × ${b} = ${S}.`,
          },
          {
            test: (_s, n) => n === a + b,
            feedback: `Стороны нужно перемножить, а не сложить. Площадь — это сколько квадратиков 1×1 поместится внутри: ${a} × ${b} = ${S}.`,
          },
        ],
        hint: 'Площадь = длина × ширина.',
      };
    }
    return {
      prompt: `Найди периметр прямоугольника со сторонами ${a} см и ${b} см.`,
      answer: String(P),
      solution: [
        `Периметр — сумма всех сторон: P = (a + b) × 2.`,
        `P = (${a} + ${b}) × 2 = ${a + b} × 2 = ${P}.`,
        `Ответ: ${P} см.`,
      ],
      mistakes: [
        {
          test: (_s, n) => n === S,
          feedback: `Ты нашёл площадь (${S}), а не периметр! Периметр — это длина всей границы: (${a} + ${b}) × 2 = ${P}.`,
        },
        {
          test: (_s, n) => n === a + b,
          feedback: `Ты сложил только две стороны, но у прямоугольника их четыре! P = (${a} + ${b}) × 2 = ${P}.`,
        },
      ],
      hint: 'Периметр = (длина + ширина) × 2.',
    };
  },
};

