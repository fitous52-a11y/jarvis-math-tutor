import type { Topic } from '../lib/types';
import { randInt, pick, fmt } from '../lib/math-utils';

// ============ 11. Проценты ============
const percent: Topic = {
  id: 'percent',
  title: 'Проценты',
  scanName: 'проценты',
  icon: 'percent',
  theory: [
    {
      kind: 'text',
      body: 'Процент — это одна сотая часть. 1% от числа — это 1/100 этого числа. Проценты везде: скидки в магазине, оценки в дневнике, заряд телефона.',
    },
    {
      kind: 'rule',
      title: 'Как найти процент от числа',
      body: '1) Делим число на 100 — узнаём, сколько в 1%.\n2) Умножаем на нужное число процентов.\nПример: 25% от 80 → 80 ÷ 100 = 0,8 → 0,8 × 25 = 20.',
    },
    {
      kind: 'example',
      title: 'Полезные проценты-коротки',
      body: '50% — это половина (÷ 2).\n25% — четверть (÷ 4).\n10% — десятая часть (÷ 10).\n20% — пятая часть (÷ 5).\n75% — три четверти.',
    },
    {
      kind: 'tip',
      body: 'Сначала ищи 10% или 1% — от них легко достроить любой процент. Например, 30% = 10% × 3.',
    },
  ],
  generate() {
    const variant = randInt(0, 1);
    if (variant === 0) {
      const p = pick([10, 20, 25, 50, 75, 30, 40]);
      const base = pick([40, 60, 80, 120, 200, 240, 300, 160]);
      const ans = (base * p) / 100;
      return {
        prompt: `Найди ${p}% от ${base}.`,
        answer: fmt(ans),
        solution: [
          `1% от ${base} — это ${base} ÷ 100 = ${fmt(base / 100)}.`,
          `${p}% — это ${fmt(base / 100)} × ${p} = ${fmt(ans)}.`,
          `Ответ: ${fmt(ans)}.`,
        ],
        mistakes: [
          {
            test: (_s, n) => n !== null && Math.abs(n - base * p) < 1e-9,
            feedback: `Ты умножил ${base} на ${p}, но забыл разделить на 100! Процент — это сотая часть. Правильно: ${base} ÷ 100 × ${p} = ${fmt(ans)}.`,
          },
          {
            test: (_s, n) => n !== null && Math.abs(n - base / p) < 1e-9,
            feedback: `Делить нужно на 100 (а потом умножать на ${p}), а не на ${p}. 1% от ${base} = ${fmt(base / 100)}, значит ${p}% = ${fmt(ans)}.`,
          },
        ],
        hint: 'Сначала найди 1% (раздели на 100), потом умножь на число процентов.',
      };
    }
    // текстовая задача на скидку
    const p = pick([10, 20, 25, 50]);
    const price = pick([300, 400, 500, 600, 800, 1200]);
    const discount = (price * p) / 100;
    const ans = price - discount;
    return {
      prompt: `Игрушка стоила ${price} рублей. На распродаже цену снизили на ${p}%.\nСколько рублей она стоит теперь?`,
      answer: fmt(ans),
      solution: [
        `Находим скидку: ${p}% от ${price} = ${price} ÷ 100 × ${p} = ${fmt(discount)} рублей.`,
        `Новая цена: ${price} − ${fmt(discount)} = ${fmt(ans)} рублей.`,
        `Ответ: ${fmt(ans)}.`,
      ],
      mistakes: [
        {
          test: (_s, n) => n !== null && Math.abs(n - discount) < 1e-9,
          feedback: `Ты нашёл СКИДКУ (${fmt(discount)} руб.) — это на сколько снизили цену. А спрашивают новую цену: ${price} − ${fmt(discount)} = ${fmt(ans)}. Всегда перечитывай вопрос задачи!`,
        },
        {
          test: (_s, n) => n !== null && Math.abs(n - (price - p)) < 1e-9,
          feedback: `${p}% — это не ${p} рублей! Процент зависит от числа: ${p}% от ${price} = ${fmt(discount)} руб. Новая цена: ${fmt(ans)} руб.`,
        },
      ],
      hint: 'Сначала найди скидку в рублях, потом вычти её из цены.',
    };
  },
};

// ============ 12. Уравнения ============
const equations: Topic = {
  id: 'equations',
  title: 'Уравнения',
  scanName: 'решение уравнений',
  icon: 'equal',
  theory: [
    {
      kind: 'text',
      body: 'Уравнение — это загадка, где вместо неизвестного числа стоит буква x. Решить уравнение — значит разгадать, чему равен x.',
    },
    {
      kind: 'rule',
      title: 'Главный приём',
      body: 'Чтобы найти x, делаем ОБРАТНОЕ действие:\nВидишь «x + 5» — вычитай 5.\nВидишь «x − 5» — прибавляй 5.\nВидишь «x × 5» — дели на 5.\nВидишь «x ÷ 5» — умножай на 5.',
    },
    {
      kind: 'example',
      title: 'Пример: x + 37 = 85',
      body: 'x спрятался за «+ 37». Обратное действие — вычитание:\nx = 85 − 37 = 48.\nПроверка: 48 + 37 = 85. Верно!',
    },
    {
      kind: 'example',
      title: 'Пример: 6 × x = 42',
      body: 'x умножили на 6 — значит, делим:\nx = 42 ÷ 6 = 7.\nПроверка: 6 × 7 = 42.',
    },
    {
      kind: 'tip',
      body: 'Всегда делай проверку: подставь найденный x в исходное уравнение. Сошлось — ты справился!',
    },
  ],
  generate() {
    const variant = randInt(0, 3);
    if (variant === 0) {
      const x = randInt(12, 89), b = randInt(11, 79);
      const sum = x + b;
      return {
        prompt: `Реши уравнение:\nx + ${b} = ${sum}`,
        answer: String(x),
        solution: [
          `x увеличили на ${b} — делаем обратное действие: вычитаем.`,
          `x = ${sum} − ${b} = ${x}.`,
          `Проверка: ${x} + ${b} = ${sum}. Верно!`,
        ],
        mistakes: [
          {
            test: (_s, n) => n === sum + b,
            feedback: `Ты прибавил ${b}, а нужно было ВЫЧЕСТЬ — действие должно быть обратным. x = ${sum} − ${b} = ${x}. Проверь: ${x} + ${b} = ${sum}.`,
          },
        ],
        hint: `Из ${sum} нужно вычесть ${b}.`,
      };
    }
    if (variant === 1) {
      const x = randInt(15, 99), b = randInt(11, x - 5);
      const diff = x - b;
      return {
        prompt: `Реши уравнение:\nx − ${b} = ${diff}`,
        answer: String(x),
        solution: [
          `Из x вычли ${b} — обратное действие: прибавляем.`,
          `x = ${diff} + ${b} = ${x}.`,
          `Проверка: ${x} − ${b} = ${diff}. Верно!`,
        ],
        mistakes: [
          {
            test: (_s, n) => n === diff - b,
            feedback: `Ты вычел ещё раз, а нужно ПРИБАВИТЬ: x = ${diff} + ${b} = ${x}. Проверка: ${x} − ${b} = ${diff}.`,
          },
        ],
        hint: `К ${diff} нужно прибавить ${b}.`,
      };
    }
    if (variant === 2) {
      const x = randInt(3, 12), b = randInt(3, 12);
      const prod = x * b;
      return {
        prompt: `Реши уравнение:\n${b} × x = ${prod}`,
        answer: String(x),
        solution: [
          `x умножили на ${b} — обратное действие: делим.`,
          `x = ${prod} ÷ ${b} = ${x}.`,
          `Проверка: ${b} × ${x} = ${prod}. Верно!`,
        ],
        mistakes: [
          {
            test: (_s, n) => n === prod * b,
            feedback: `Ты умножил, а нужно ДЕЛИТЬ: x = ${prod} ÷ ${b} = ${x}. В уравнении всегда делаем действие, обратное тому, что сделано с x.`,
          },
        ],
        hint: `${prod} раздели на ${b}.`,
      };
    }
    const x = randInt(4, 25), b = randInt(2, 9);
    const q = x;
    const dividend = x * b;
    return {
      prompt: `Реши уравнение:\nx ÷ ${b} = ${q}`,
      answer: String(x),
      solution: [
        `x разделили на ${b} — обратное действие: умножаем.`,
        `x = ${q} × ${b} = ${dividend}.`,
        `Проверка: ${dividend} ÷ ${b} = ${q}. Верно!`,
      ],
      mistakes: [
        {
          test: (_s, n) => n !== null && Math.abs(n - q / b) < 1e-9,
          feedback: `Ты разделил, а нужно УМНОЖИТЬ: x = ${q} × ${b} = ${dividend}. Проверка: ${dividend} ÷ ${b} = ${q}.`,
        },
      ],
      hint: `${q} умножь на ${b}.`,
    };
  },
};

// ============ 13. Текстовые задачи ============
const word: Topic = {
  id: 'word',
  title: 'Текстовые задачи',
  scanName: 'текстовые задачи на движение и стоимость',
  icon: 'route',
  theory: [
    {
      kind: 'text',
      body: 'Текстовая задача — это история, которую нужно перевести на язык математики. Главное — понять, ЧТО известно и ЧТО спрашивают.',
    },
    {
      kind: 'rule',
      title: 'Волшебный треугольник скорости',
      body: 'Путь = скорость × время (S = v × t).\nСкорость = путь ÷ время (v = S ÷ t).\nВремя = путь ÷ скорость (t = S ÷ v).\nКого ищем — того «прикрываем ладонью»: остальное и есть формула.',
    },
    {
      kind: 'example',
      title: 'Пример: велосипедист',
      body: 'Велосипедист ехал 3 часа со скоростью 12 км/ч. Какой путь он проехал?\nS = v × t = 12 × 3 = 36 км.',
    },
    {
      kind: 'rule',
      title: 'Цена, количество, стоимость',
      body: 'Стоимость = цена × количество.\nЦена = стоимость ÷ количество.\nРаботает так же, как треугольник скорости!',
    },
    {
      kind: 'tip',
      body: 'После решения спроси себя: «Ответ похож на правду?» Если пешеход прошёл 300 км за час — где-то перепутано действие.',
    },
  ],
  generate() {
    const variant = randInt(0, 2);
    if (variant === 0) {
      const v = randInt(4, 18), t = randInt(2, 6);
      const s = v * t;
      const who = pick(['Велосипедист ехал', 'Теплоход плыл', 'Автобус ехал']);
      return {
        prompt: `${who} ${t} ч со скоростью ${v} км/ч.\nКакой путь пройден за это время? (ответ в километрах, запиши число)`,
        answer: String(s),
        solution: [
          `Путь = скорость × время: S = v × t.`,
          `S = ${v} × ${t} = ${s} км.`,
          `Ответ: ${s}.`,
        ],
        mistakes: [
          {
            test: (_s, n) => n !== null && Math.abs(n - v / t) < 1e-9,
            feedback: `Ты разделил скорость на время, а путь находится УМНОЖЕНИЕМ: S = v × t = ${v} × ${t} = ${s}. Вспомни треугольник: путь наверху, его «закрываем» — остаётся v × t.`,
          },
          {
            test: (_s, n) => n === v + t,
            feedback: `Скорость и время нужно перемножить, а не сложить! S = ${v} × ${t} = ${s} км.`,
          },
        ],
        hint: 'S = v × t.',
      };
    }
    if (variant === 1) {
      const v = randInt(4, 20), t = randInt(2, 7);
      const s = v * t;
      return {
        prompt: `Поезд проехал ${s} км за ${t} ч, двигаясь с постоянной скоростью.\nС какой скоростью он ехал? (км/ч, запиши число)`,
        answer: String(v),
        solution: [
          `Скорость = путь ÷ время: v = S ÷ t.`,
          `v = ${s} ÷ ${t} = ${v} км/ч.`,
          `Ответ: ${v}.`,
        ],
        mistakes: [
          {
            test: (_s, n) => n !== null && Math.abs(n - t / s) < 1e-9,
            feedback: `Ты разделил время на путь — получилось «сколько часов на километр». Скорость — это путь за один час: v = ${s} ÷ ${t} = ${v} км/ч.`,
          },
          {
            test: (_s, n) => n === s * t,
            feedback: `Путь и время нужно разделить, а не умножить! Умножение дало бы ${s * t} — нереальную скорость. v = ${s} ÷ ${t} = ${v}.`,
          },
        ],
        hint: 'v = S ÷ t.',
      };
    }
    const price = randInt(15, 90), count = randInt(3, 9);
    const cost = price * count;
    return {
      prompt: `За ${count} одинаковых тетрадей заплатили ${cost} рублей.\nСколько стоит одна тетрадь? (рублей, запиши число)`,
      answer: String(price),
      solution: [
        `Цена = стоимость ÷ количество.`,
        `${cost} ÷ ${count} = ${price} рублей.`,
        `Ответ: ${price}.`,
      ],
      mistakes: [
        {
          test: (_s, n) => n === cost * count,
          feedback: `Если умножить, одна тетрадь будет стоить ${cost * count} рублей — дороже всей покупки! Делим: ${cost} ÷ ${count} = ${price}.`,
        },
      ],
      hint: 'Стоимость раздели на количество.',
    };
  },
};

export const topicsPart3: Topic[] = [percent, equations, word];
