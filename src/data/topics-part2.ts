import type { Topic } from '../lib/types';
import { randInt, pick, fmt, frac, gcd } from '../lib/math-utils';

// ============ 6. Обыкновенные дроби ============
const fractions: Topic = {
  id: 'fractions',
  title: 'Обыкновенные дроби',
  scanName: 'понятие обыкновенной дроби',
  icon: 'pie',
  theory: [
    {
      kind: 'text',
      body: 'Дробь — это часть целого. Если пиццу разрезали на 8 равных кусков и ты взял 3, то у тебя 3/8 пиццы.',
    },
    {
      kind: 'rule',
      title: 'Что есть что в дроби',
      body: 'Внизу — знаменатель: на сколько равных частей разделили целое.\nВверху — числитель: сколько таких частей взяли.\nЗапомни: знаменатель внизу, как фундамент дома.',
    },
    {
      kind: 'example',
      title: 'Сравнение дробей',
      body: 'У дробей с одинаковым знаменателем больше та, у которой больше числитель: 5/8 > 3/8 (пять кусков больше трёх).\nУ дробей с одинаковым числителем больше та, у которой меньше знаменатель: 1/3 > 1/5 (если пиццу делят на троих, куски больше, чем если на пятерых).',
    },
    {
      kind: 'tip',
      body: 'Представляй дробь как куски пиццы или шоколадки — сразу становится понятно, какая дробь больше.',
    },
  ],
  generate() {
    const variant = randInt(0, 1);
    if (variant === 0) {
      const d = pick([6, 8, 9, 10, 12]);
      const n = randInt(2, d - 2);
      return {
        prompt: `Шоколадку разделили на ${d} равных долек. Миша съел ${n} дольки.\nКакую часть шоколадки он съел? (ответ запиши дробью, например 3/8)`,
        answer: frac(n, d),
        alsoAccept: [`${n}/${d}`],
        solution: [
          `Всего частей: ${d} — это знаменатель (пишем внизу).`,
          `Взяли ${n} — это числитель (пишем вверху).`,
          `Ответ: ${n}/${d}${gcd(n, d) > 1 ? ` = ${frac(n, d)} (можно сократить)` : ''}.`,
        ],
        mistakes: [
          {
            test: (s) => s === `${d}/${n}`,
            feedback: `Ты перевернул дробь! Знаменатель (на сколько частей разделили — ${d}) всегда пишется ВНИЗУ, а числитель (сколько взяли — ${n}) — ВВЕРХУ. Правильно: ${n}/${d}.`,
          },
        ],
        hint: 'Внизу — на сколько разделили, вверху — сколько взяли.',
      };
    }
    const d = pick([7, 8, 9, 11, 12]);
    const n1 = randInt(1, d - 2);
    let n2 = randInt(1, d - 1);
    while (n2 === n1) n2 = randInt(1, d - 1);
    const big = Math.max(n1, n2), small = Math.min(n1, n2);
    const first = Math.random() < 0.5 ? n1 : n2;
    const second = first === n1 ? n2 : n1;
    return {
      prompt: `Какая дробь больше: ${first}/${d} или ${second}/${d}?\n(запиши бóльшую дробь, например 3/8)`,
      answer: `${big}/${d}`,
      solution: [
        `Знаменатели одинаковые (${d}) — значит, куски одного размера.`,
        `Больше та дробь, у которой больше числитель: ${big} > ${small}.`,
        `Ответ: ${big}/${d}.`,
      ],
      mistakes: [
        {
          test: (s) => s === `${small}/${d}`,
          feedback: `При одинаковом знаменателе сравниваем числители: ${big} кусков больше, чем ${small}. Значит, ${big}/${d} больше.`,
        },
      ],
      hint: 'Знаменатели одинаковые — сравнивай числители.',
    };
  },
};

// ============ 7. Сложение и вычитание дробей ============
const fracadd: Topic = {
  id: 'fracadd',
  title: 'Сложение дробей',
  scanName: 'сложение и вычитание обыкновенных дробей',
  icon: 'sigma',
  theory: [
    {
      kind: 'text',
      body: 'Складывать дроби — как складывать куски пиццы. Если куски одинакового размера (знаменатели равны), просто считаем куски.',
    },
    {
      kind: 'rule',
      title: 'Одинаковые знаменатели',
      body: 'Складываем (или вычитаем) только числители, а знаменатель оставляем тем же:\n2/7 + 3/7 = 5/7.\nЗнаменатель НЕ складывается!',
    },
    {
      kind: 'rule',
      title: 'Разные знаменатели',
      body: 'Сначала приводим дроби к общему знаменателю — делаем куски одинакового размера. Например, 1/2 + 1/4: половинку режем пополам → 2/4 + 1/4 = 3/4.',
    },
    {
      kind: 'example',
      title: 'Пример: 1/2 + 1/4',
      body: 'Половинка — это две четверти: 1/2 = 2/4.\nТогда 2/4 + 1/4 = 3/4.',
    },
    {
      kind: 'tip',
      body: 'Главная ловушка темы: складывать и числители, и знаменатели. 1/2 + 1/4 НЕ равно 2/6! Проверяй себя на пицце.',
    },
  ],
  generate() {
    if (Math.random() < 0.5) {
      const d = pick([7, 9, 11, 13, 15]);
      const n1 = randInt(1, d - 3);
      const n2 = randInt(1, d - n1 - 1);
      const ans = n1 + n2;
      return {
        prompt: `Вычисли:\n${n1}/${d} + ${n2}/${d}\n(ответ запиши дробью, например 5/7)`,
        answer: frac(ans, d),
        alsoAccept: [`${ans}/${d}`],
        solution: [
          `Знаменатели одинаковые — складываем только числители.`,
          `${n1} + ${n2} = ${ans}. Знаменатель остаётся ${d}.`,
          `Ответ: ${ans}/${d}${gcd(ans, d) > 1 ? ` = ${frac(ans, d)}` : ''}.`,
        ],
        mistakes: [
          {
            test: (s) => s === `${ans}/${d * 2}`,
            feedback: `Ты сложил и знаменатели! Знаменатель — это размер куска, он не меняется. Складываем только числители: ${n1} + ${n2} = ${ans}, знаменатель остаётся ${d}. Ответ: ${ans}/${d}.`,
          },
        ],
        hint: 'Знаменатель оставь тем же, сложи только числители.',
      };
    }
    // разные знаменатели: 1/a + 1/(2a) или 1/2 + 1/4 и т.п.
    const pairs: Array<[number, number]> = [[2, 4], [2, 6], [3, 6], [2, 8], [4, 8], [3, 9], [2, 10], [5, 10]];
    const [d1, d2] = pick(pairs);
    const n1 = randInt(1, d1 - 1), n2 = randInt(1, d2 - 1);
    const num = n1 * (d2 / d1) + n2;
    return {
      prompt: `Вычисли:\n${n1}/${d1} + ${n2}/${d2}\n(ответ запиши дробью, например 3/4)`,
      answer: frac(num, d2),
      alsoAccept: [`${num}/${d2}`],
      solution: [
        `Знаменатели разные — приводим к общему: ${n1}/${d1} = ${n1 * (d2 / d1)}/${d2}.`,
        `Теперь складываем: ${n1 * (d2 / d1)}/${d2} + ${n2}/${d2} = ${num}/${d2}.`,
        `Ответ: ${frac(num, d2)}.`,
      ],
      mistakes: [
        {
          test: (s) => s === `${n1 + n2}/${d1 + d2}`,
          feedback: `Нельзя складывать числители и знаменатели напрямую! Сначала приведи дроби к общему знаменателю: ${n1}/${d1} — это ${n1 * (d2 / d1)}/${d2}. Тогда ${n1 * (d2 / d1)}/${d2} + ${n2}/${d2} = ${frac(num, d2)}.`,
        },
        {
          test: (s) => s === `${n1 + n2}/${d2}`,
          feedback: `Знаменатель общий ты нашёл, но первую дробь забыл преобразовать: ${n1}/${d1} = ${n1 * (d2 / d1)}/${d2}. Если знаменатель умножили на ${d2 / d1}, числитель тоже умножаем на ${d2 / d1}!`,
        },
      ],
      hint: `Приведи ${n1}/${d1} к знаменателю ${d2}.`,
    };
  },
};

// ============ 8. Десятичные дроби ============
const decimals: Topic = {
  id: 'decimals',
  title: 'Десятичные дроби',
  scanName: 'запись и сравнение десятичных дробей',
  icon: 'dot',
  theory: [
    {
      kind: 'text',
      body: 'Десятичная дробь — это способ записать «нецелое» число через запятую. 2,5 — это две целых и пять десятых (половинка).',
    },
    {
      kind: 'rule',
      title: 'Разряды после запятой',
      body: 'Первая цифра после запятой — десятые (0,1 = 1/10).\nВторая — сотые (0,01 = 1/100).\nТретья — тысячные (0,001 = 1/1000).',
    },
    {
      kind: 'example',
      title: 'Сравнение: 0,7 и 0,65',
      body: 'Приписываем ноль: 0,7 = 0,70.\nТеперь сравниваем 70 сотых и 65 сотых: 0,70 > 0,65.\nЗначит, 0,7 > 0,65. Больше цифр после запятой — НЕ значит больше число!',
    },
    {
      kind: 'tip',
      body: 'Нули в конце дробной части ничего не меняют: 0,5 = 0,50 = 0,500. Но ноль СРАЗУ после запятой — меняет: 0,5 ≠ 0,05.',
    },
  ],
  generate() {
    const variant = randInt(0, 1);
    if (variant === 0) {
      const a = randInt(11, 99) / 10; // x,x
      const b = a - randInt(1, 9) / 100 + (Math.random() < 0.5 ? 0 : randInt(1, 9) / 100);
      // гарантируем b с сотыми и отличие
      const aR = Math.round(a * 100) / 100;
      let bR = Math.round(b * 100) / 100;
      if (bR === aR) bR = aR - 0.05;
      const big = Math.max(aR, bR), small = Math.min(aR, bR);
      const flip = Math.random() < 0.5;
      return {
        prompt: `Какое число больше: ${fmt(flip ? small : big)} или ${fmt(flip ? big : small)}?`,
        answer: fmt(big),
        solution: [
          `Уравниваем разряды: ${fmt(big)} = ${fmt(Math.round(big * 100) / 100)}.`,
          `Сравниваем сотые: у ${fmt(big)} больше.`,
          `Ответ: ${fmt(big)}.`,
        ],
        mistakes: [
          {
            test: (_s, n) => n === small,
            feedback: `Ловушка: больше цифр после запятой — не значит больше число! Припиши ноль и сравни сотые: ${fmt(big)} против ${fmt(small)}. Больше ${fmt(big)}.`,
          },
        ],
        hint: 'Припиши нули, чтобы после запятой было поровну цифр, и сравни.',
      };
    }
    const units = randInt(1, 9);
    const hundredths = randInt(1, 9);
    const words = ['одна', 'две', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'];
    const unitsWords = ['одна целая', 'две целых', 'три целых', 'четыре целых', 'пять целых', 'шесть целых', 'семь целых', 'восемь целых', 'девять целых'];
    return {
      prompt: `Запиши цифрами число:\n«${unitsWords[units - 1]} ${words[hundredths - 1]} сотых»\n(используй запятую)`,
      answer: fmt(units + hundredths / 100),
      solution: [
        `Целая часть: ${units} — пишем до запятой.`,
        `Сотые — это ВТОРАЯ цифра после запятой. Если десятых нет — ставим 0.`,
        `Ответ: ${units},0${hundredths}.`,
      ],
      mistakes: [
        {
          test: (_s, n) => n !== null && Math.abs(n - (units + hundredths / 10)) < 1e-9,
          feedback: `Ты записал сотые как десятые! Сотые — вторая цифра после запятой: ${units},0${hundredths}. А ${units},${hundredths} — это «${words[hundredths - 1]} десятых».`,
        },
      ],
      hint: 'Сотые — вторая цифра после запятой. Не забудь ноль в десятых!',
    };
  },
};

// ============ 9. Сложение и вычитание десятичных ============
const decadd: Topic = {
  id: 'decadd',
  title: 'Действия с десятичными',
  scanName: 'сложение и вычитание десятичных дробей',
  icon: 'align-left',
  theory: [
    {
      kind: 'text',
      body: 'Десятичные дроби складываются столбиком почти как обычные числа. Есть только одно важное правило.',
    },
    {
      kind: 'rule',
      title: 'Запятая под запятой!',
      body: 'Записываем числа так, чтобы запятая оказалась строго под запятой. Если цифр после запятой не хватает — приписываем нули: 2,35 + 1,4 = 2,35 + 1,40.',
    },
    {
      kind: 'example',
      title: 'Пример: 2,35 + 1,4',
      body: 'Записываем:\n  2,35\n+ 1,40\nСкладываем как обычно: 5 + 0 = 5; 3 + 4 = 7; 2 + 1 = 3.\nОтвет: 3,75.',
    },
    {
      kind: 'tip',
      body: 'Самая частая ошибка — записать числа «по правому краю», как целые. Тогда 1,4 окажется под 0,05 — и всё поедет. Только запятая под запятой!',
    },
  ],
  generate() {
    const plus = Math.random() < 0.5;
    const a = randInt(11, 999) / 100; // два знака
    const b = randInt(11, 99) / 10;   // один знак
    const ans = plus ? a + b : a - b;
    const ansR = Math.round(ans * 100) / 100;
    const wrongAlign = plus ? a + b / 10 : a - b / 10; // классическая ошибка выравнивания
    const wrongR = Math.round(wrongAlign * 1000) / 1000;
    return {
      prompt: `Вычисли:\n${fmt(a)} ${plus ? '+' : '−'} ${fmt(b)}\n(ответ запиши через запятую)`,
      answer: fmt(ansR),
      solution: [
        `Записываем столбиком запятая под запятой: ${fmt(b)} = ${fmt(b)}0.`,
        `${fmt(a)} ${plus ? '+' : '−'} ${fmt(Math.round(b * 10) / 10)}0 → считаем как обычные числа.`,
        `Ответ: ${fmt(ansR)}.`,
      ],
      mistakes: [
        {
          test: (_s, n) => n !== null && Math.abs(n - wrongR) < 0.001,
          feedback: `Ты записал числа по правому краю, а не запятую под запятой! ${fmt(b)} — это ${fmt(Math.round(b * 10) / 10)}0: десятые под десятыми. Перепиши столбик: ${fmt(a)} и ${fmt(b)}0, и получится ${fmt(ansR)}.`,
        },
        {
          test: (_s, n) => n !== null && Math.abs(Math.abs(n - ansR) - 0.1) < 0.001,
          feedback: 'Ошибка на одну десятую — потерялся перенос (или занимание) в разряде десятых. Пересчитай столбик, следя за переносами.',
        },
      ],
      hint: 'Запятая строго под запятой, недостающие цифры дополни нулями.',
    };
  },
};

// ============ 10. Умножение и деление десятичных ============
const decmul: Topic = {
  id: 'decmul',
  title: 'Умножение десятичных',
  scanName: 'умножение и деление десятичных дробей',
  icon: 'asterisk',
  theory: [
    {
      kind: 'text',
      body: 'Умножать десятичные дроби просто: сначала умножаем, вообще не глядя на запятые, а потом возвращаем запятую на место.',
    },
    {
      kind: 'rule',
      title: 'Правило запятой',
      body: '1) Умножаем числа, не обращая внимания на запятые.\n2) Считаем, сколько цифр после запятой в ОБОИХ множителях вместе.\n3) Столько же цифр отделяем запятой в ответе, считая справа.',
    },
    {
      kind: 'example',
      title: 'Пример: 0,6 × 0,4',
      body: '6 × 4 = 24.\nЦифр после запятой: одна + одна = две.\nОтделяем две цифры справа: 0,24. (Не 2,4!)',
    },
    {
      kind: 'example',
      title: 'Умножение на 10, 100, 1000',
      body: 'Запятая прыгает вправо на столько цифр, сколько нулей: 3,25 × 100 = 325. При делении на 10, 100 — запятая прыгает влево: 47,5 ÷ 10 = 4,75.',
    },
    {
      kind: 'tip',
      body: 'Проверка на здравый смысл: 0,6 × 0,4 — это «больше половины от 0,4», значит ответ должен быть меньше 0,4. 2,4 больше 0,4 — сразу видно ошибку!',
    },
  ],
  generate() {
    const variant = randInt(0, 2);
    if (variant === 0) {
      const a = randInt(2, 9) / 10, b = randInt(2, 9) / 10;
      const ans = Math.round(a * b * 100) / 100;
      return {
        prompt: `Вычисли:\n${fmt(a)} × ${fmt(b)}`,
        answer: fmt(ans),
        solution: [
          `Умножаем без запятых: ${a * 10} × ${b * 10} = ${a * 10 * b * 10}.`,
          `Цифр после запятой в обоих числах: 2. Отделяем 2 цифры справа.`,
          `Ответ: ${fmt(ans)}.`,
        ],
        mistakes: [
          {
            test: (_s, n) => n !== null && Math.abs(n - ans * 10) < 1e-9,
            feedback: `Ты отделил запятой одну цифру, а нужно ДВЕ — ведь в обоих множителях вместе две цифры после запятой. ${a * 10} × ${b * 10} = ${a * 10 * b * 10} → отделяем две цифры: ${fmt(ans)}. Проверка: ответ должен быть меньше обоих множителей!`,
          },
        ],
        hint: 'Посчитай цифры после запятой в обоих числах — столько же отдели в ответе.',
      };
    }
    if (variant === 1) {
      const a = randInt(13, 98) / 10;
      const m = pick([10, 100, 1000]);
      const ans = a * m;
      const wrongDir = a / m;
      return {
        prompt: `Вычисли:\n${fmt(a)} × ${m}`,
        answer: fmt(Math.round(ans * 1000) / 1000),
        solution: [
          `При умножении на ${m} запятая прыгает ВПРАВО на ${String(m).length - 1} цифру(ы).`,
          `${fmt(a)} × ${m} = ${fmt(Math.round(ans * 1000) / 1000)}.`,
        ],
        mistakes: [
          {
            test: (_s, n) => n !== null && Math.abs(n - Math.round(wrongDir * 10000) / 10000) < 1e-9,
            feedback: `Запятая прыгнула не в ту сторону! При УМНОЖЕНИИ на ${m} число становится больше — запятая идёт ВПРАВО: ${fmt(a)} × ${m} = ${fmt(Math.round(ans * 1000) / 1000)}. Влево она идёт при делении.`,
          },
        ],
        hint: `Умножение на ${m} — запятая вправо на ${String(m).length - 1}.`,
      };
    }
    // деление десятичной на натуральное
    const b = randInt(2, 9);
    const q = randInt(11, 99) / 10;
    const a = Math.round(q * b * 10) / 10;
    return {
      prompt: `Вычисли:\n${fmt(a)} ÷ ${b}`,
      answer: fmt(q),
      solution: [
        `Делим как обычно, а запятую в ответе ставим, когда доходим до неё в делимом.`,
        `${fmt(a)} ÷ ${b} = ${fmt(q)}. Проверка: ${fmt(q)} × ${b} = ${fmt(a)}.`,
      ],
      mistakes: [
        {
          test: (_s, n) => n !== null && Math.abs(n - q * 10) < 1e-9,
          feedback: `Забыл поставить запятую в ответе! Как только при делении уголком дошли до запятой в делимом — сразу ставим запятую в ответе. Правильно: ${fmt(q)}.`,
        },
        {
          test: (_s, n) => n !== null && Math.abs(n - q / 10) < 1e-9,
          feedback: `Запятая встала на один разряд левее. Проверь умножением: ${fmt(q)} × ${b} = ${fmt(a)} — значит, ответ ${fmt(q)}.`,
        },
      ],
      hint: 'Дели как обычные числа, не забудь запятую в ответе.',
    };
  },
};

